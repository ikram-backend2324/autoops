#!/usr/bin/env python3
"""Create demo copies of the alert rules with `for:` capped at 1 minute.

Production rules wait (e.g. HighCPU fires after 10 minutes); for the laptop demo and
the chaos video we want the same alerts within a minute. Output: local/generated/rules/.
The production files in stacks/monitoring/prometheus/rules/ are never modified.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "stacks/monitoring/prometheus/rules"
DST = ROOT / "local/generated/rules"
UNITS = {"s": 1, "m": 60, "h": 3600, "d": 86400}
CAP_SECONDS = 60
# Longer waits (e.g. "no backup for 26h") are semantic, not demo latency - keep them.
MAX_CAPPABLE_SECONDS = 3600
PATTERN = re.compile(r"^(\s*for:\s*)(\d+)([smhd])\s*$", re.MULTILINE)


def cap(match: re.Match) -> str:
    seconds = int(match.group(2)) * UNITS[match.group(3)]
    if seconds <= CAP_SECONDS or seconds > MAX_CAPPABLE_SECONDS:
        return match.group(0)
    return f"{match.group(1)}1m  # demo: production value {match.group(2)}{match.group(3)}"


def main() -> int:
    DST.mkdir(parents=True, exist_ok=True)
    for old in DST.glob("*.yml"):
        old.unlink()
    for src in sorted(SRC.glob("*.yml")):
        text = "# GENERATED by scripts/dev/fast_rules.py - edit the production rules instead.\n"
        text += PATTERN.sub(cap, src.read_text(encoding="utf-8"))
        (DST / src.name).write_text(text, encoding="utf-8", newline="\n")
    print(f"demo rules written to {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
