#!/usr/bin/env bash
# Run every chaos scenario, print a summary table and write docs/chaos-report.md.
#   CHAOS_NONINTERACTIVE=1  no "press Enter" pauses
#   CHAOS_ONLY="1 3"        run a subset
source "$(dirname "$0")/lib.sh"
preflight

ROOT=$(cd "$CHAOS_DIR/../.." && pwd)
REPORT=${CHAOS_REPORT:-$ROOT/docs/chaos-report.md}
: > "$RESULTS_FILE"
START=$(date +%s)
scenarios=(kill_container.sh make_unhealthy.sh stop_db.sh fill_disk.sh cpu_stress.sh)
only=${CHAOS_ONLY:-1 2 3 4 5}

printf '%s\n' "${C_BOLD}AutoOps chaos demo${C_RESET} — приложение '$CHAOS_APP', проверка: $APP_HEALTH_URL"
printf '%s\n' "Каждый сценарий ломает систему и измеряет, как быстро она это замечает, лечит себя и сообщает."

i=0
for script in "${scenarios[@]}"; do
  i=$((i + 1))
  [[ " $only " == *" $i "* ]] || continue
  if [[ -z "${CHAOS_NONINTERACTIVE:-}" && -t 0 ]]; then
    read -r -p "$(printf '\n%s' "${C_YELLOW}Enter — запустить сценарий $i ($script), Ctrl+C — выход${C_RESET} ")" _
  fi
  "$CHAOS_DIR/$script" || true
  # let alerts resolve and the stack settle before the next scenario
  if (( i < 5 )); then
    step "пауза 20 с перед следующим сценарием…"
    sleep 20
  fi
done

printf '\n%s\n' "${C_BOLD}Итог${C_RESET}"
printf '%-30s %-14s %-16s %-36s %s\n' "Сценарий" "Обнаружено, с" "Восстановлено, с" "Оповещение" "Результат"
while IFS=$'\t' read -r sc det rec al res; do
  color=$C_GREEN; [[ $res == PASS ]] || color=$C_RED
  printf '%-30s %-14s %-16s %-36s %s\n' "$sc" "$det" "$rec" "$al" "${color}${res}${C_RESET}"
done < "$RESULTS_FILE"

passed=$(grep -c $'\tPASS$' "$RESULTS_FILE" || true)
total=$(wc -l < "$RESULTS_FILE" | tr -d ' ')

{
  echo "# Chaos report"
  echo
  echo "Generated by \`make chaos\` on $(date '+%Y-%m-%d %H:%M %Z') — app \`$CHAOS_APP\`, health URL \`$APP_HEALTH_URL\`,"
  echo "Docker $(docker version --format '{{.Server.Version}}'), $(docker info --format '{{.NCPU}}') CPU, OS: $(docker info --format '{{.OperatingSystem}}')."
  echo
  echo "Result: **$passed / $total scenarios passed**, total run time $(( ($(date +%s) - START) / 60 )) min."
  echo
  echo "Times are seconds from the moment of failure injection."
  echo
  echo "| Сценарий | Обнаружено за, с | Восстановлено за, с | Оповещение | Результат |"
  echo "|---|---|---|---|---|"
  while IFS=$'\t' read -r sc det rec al res; do
    echo "| $sc | $det | $rec | $al | $res |"
  done < "$RESULTS_FILE"
  echo
  echo "## How each failure was handled"
  echo
  echo "1. **Killed web** — Docker restart policy (\`restart: unless-stopped\`) restarts the container; Prometheus/cAdvisor notice the restart → \`ContainerRestarted\` (info, silent in Telegram)."
  echo "2. **Unhealthy web** — Docker healthcheck marks it unhealthy after 3 failures, \`autoheal\` restarts it and posts to notify-relay → Telegram."
  echo "3. **Postgres stopped** — a manual stop is not covered by restart policies; \`PostgresDown\` (critical) fires and the watchdog restarts the stack after its grace period."
  echo "4. **Disk full** — the watchdog sees >85 %, removes known garbage (and on servers prunes old Docker data), and reports how much it freed."
  echo "5. **CPU saturated** — \`HighCPU\` fires (demo rules: 1 min, production: 10 min); there is nothing safe to auto-heal, a human is notified."
  echo
  echo "## Events received by notify-relay during the run"
  echo
  echo '```'
  curl -fsS -m 5 "$RELAY_URL/events?since=$START&limit=200" 2>/dev/null | tr '{' '\n' \
    | sed -nE 's/.*"kind": "alert", "status": "([a-z]+)", "alertname": "([^"]+)", "severity": "([a-z]+)".*/alert  \1  \2 (\3)/p; s/.*"kind": "notify", "severity": "([a-z]+)", "source": "([a-z]+)", "text": "([^"]{0,140}).*/notify \2 (\1): \3/p' \
    | sed 's/\\n/ /g'
  echo '```'
} > "$REPORT"

printf '\n%s\n' "Отчёт сохранён: ${C_BOLD}$REPORT${C_RESET}  ($passed/$total PASS)"
[[ "$passed" == "$total" ]]
